async def stream_reply(prompt: str):
    """Yield SSE chunks word-by-word to simulate token streaming."""
    reply = random.choice(CANNED_REPLIES)
    if "?" not in prompt and len(prompt) < 20:
        reply = (
            f"You said: “{prompt}”. Here's a thoughtful response to get us started — "
            "this is a demo reply generated by the backend. Swap `stream_reply()` in "
            "`main.py` with a call to your favorite LLM API to make it real!\n\n"
            "The text streams here word by word, just like Claude does."
        )

    words = reply.split(" ")
    for i, word in enumerate(words):
        chunk = word if i == 0 else " " + word
        yield f"data: {json.dumps({'text': chunk})}\n\n"
        await _sleep(0.02 + random.random() * 0.03)
    yield "data: [DONE]\n\n"


async def _sleep(seconds: float):
    import asyncio

    await asyncio.sleep(seconds)


# --- Routes -----------------------------------------------------------------


@app.post("/api/chat")
async def chat(req: ChatRequest):
    last_user = next(
        (m.content for m in reversed(req.messages) if m.role == "user"), ""
    )
    return StreamingResponse(
        stream_reply(last_user),
        media_type="text/event-stream",
        headers={"Cache-Control": "no-cache", "X-Accel-Buffering": "no"},
    )


@app.get("/health")
async def health():
    return {"status": "ok", "time": time.time()}


@app.get("/")
async def index():
    return FileResponse(STATIC_DIR / "index.html")


app.mount("/static", StaticFiles(directory=STATIC_DIR), name="static")
